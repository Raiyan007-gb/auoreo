"""Tool catalog drift guard (spec §20.4 `verify-tool-catalog --check`).

`docs/catalog/tools.md` is GENERATED from the bundled `tools/*/tool.yaml` folders (one row per
tool: toolset, permission, default action, egress class, exposure, sandbox mode). Regenerate,
don't edit:

    uv run python scripts/verify_tool_catalog.py --write   # after adding/changing a tool
    uv run python scripts/verify_tool_catalog.py --check   # CI: exit 1 on drift (names the tools)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "docs" / "catalog" / "tools.md"
HEADER = """# Tool catalog

Generated by `scripts/verify_tool_catalog.py --write` from `tools/*/tool.yaml`; CI runs
`--check`. Do not edit by hand. `net` is the egress class enforced by the executor
(`none` | `proxy` = through the loopback egress proxy | `direct` = approval + justification).

| tool | toolset | permission | default | net | exposure | sandbox |
|---|---|---|---|---|---|---|
"""


def rows(root: Path = ROOT) -> list[dict[str, str]]:
    out = []
    for path in sorted((root / "tools").glob("*/tool.yaml")):
        m = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        name = str(m.get("name", path.parent.name))
        out.append(
            {
                "name": name,
                "folder": path.parent.name,
                "toolset": str(m.get("toolset", "")),
                "permission": str(m.get("permission") or name),
                "default": str(m.get("default_action", "ask")),
                "net": str(m.get("net", "none")),
                "exposure": str(m.get("exposure", "direct")),
                "sandbox": str(m.get("sandbox_mode", "workspace-write")),
            }
        )
    return out


def render(items: list[dict[str, str]]) -> str:
    lines = [
        f"| `{r['name']}` | {r['toolset']} | {r['permission']} | {r['default']} | {r['net']} | "
        f"{r['exposure']} | {r['sandbox']} |"
        for r in items
    ]
    return HEADER + "\n".join(lines) + f"\n\n{len(items)} tools.\n"


def problems(root: Path = ROOT, catalog: Path = CATALOG) -> list[str]:
    items = rows(root)
    out = [f"tools/{r['folder']}: name '{r['name']}' != folder" for r in items if r["name"] != r["folder"]]
    if not catalog.is_file():
        return [*out, f"{catalog.relative_to(root)} is missing (run --write)"]
    have = catalog.read_text(encoding="utf-8")
    if have != render(items):
        listed = {line.split("`")[1] for line in have.splitlines() if line.startswith("| `")}
        names = {r["name"] for r in items}
        out += [f"undocumented tool: {n}" for n in sorted(names - listed)]
        out += [f"catalog lists a missing tool: {n}" for n in sorted(listed - names)]
        if not (names ^ listed):
            out.append("a tool's toolset/permission/default/net/exposure/sandbox changed")
        out.append(f"{catalog.relative_to(root)} is stale (run scripts/verify_tool_catalog.py --write)")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = ap.parse_args(argv)
    if args.write:
        CATALOG.parent.mkdir(parents=True, exist_ok=True)
        CATALOG.write_text(render(rows()), encoding="utf-8")
        print(f"wrote {CATALOG.relative_to(ROOT)}")
        return 0
    found = problems()
    for p in found:
        print(p, file=sys.stderr)
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
