""".env.example lists every variable AUOREO reads, and is safe to copy as-is.

The file is generated by `scripts/gen_env_example.py` from the Settings model plus the provider,
tool and backend keys; these tests fail when a setting or a declared key is missing, when a name
a project `.env` may not set carries a value, or when copying the file in produces warnings.
"""

from __future__ import annotations

import logging
import os
import re
import subprocess
import sys
from pathlib import Path

import pytest
import yaml
from dotenv import dotenv_values

from auoreo.core import dotenv
from auoreo.core.settings import Settings

ROOT = Path(__file__).resolve().parents[2]
EXAMPLE = ROOT / ".env.example"
ASSIGN = re.compile(r"^([A-Z][A-Z0-9_]*)=(.*)$", re.M)
CONST = re.compile(r"^\s*(?:KEY|KEYS|TOKEN)\s*=\s*(.+)$", re.M)
ENV_NAME = re.compile(r'"([A-Z][A-Z0-9_]+)"')


def _assignments() -> list[tuple[str, str]]:
    return ASSIGN.findall(EXAMPLE.read_text(encoding="utf-8"))


def _declared_keys() -> set[str]:
    """`requires_env` of every tool/backend/plugin manifest + backend/plugin key constants."""
    names: set[str] = set()
    for pattern in ("tools/*/tool.yaml", "backends/*/*/backend.yaml", "plugins/*/plugin.yaml"):
        for path in ROOT.glob(pattern):
            manifest = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
            names |= set(manifest.get("requires_env") or [])
    for pattern in ("backends/*/*/impl.py", "plugins/*/plugin.py"):
        for path in ROOT.glob(pattern):
            for rhs in CONST.findall(path.read_text(encoding="utf-8")):
                names |= set(ENV_NAME.findall(rhs))
    return names


def test_generated_file_is_current() -> None:
    proc = subprocess.run(
        [sys.executable, str(ROOT / "scripts" / "gen_env_example.py"), "--check"],
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr


def test_every_setting_is_listed_once() -> None:
    names = [n for n, _ in _assignments()]
    dupes = sorted({n for n in names if names.count(n) > 1})
    assert not dupes, dupes
    missing = sorted(
        f"AUOREO_{f.upper()}" for f in Settings.model_fields if f"AUOREO_{f.upper()}" not in names
    )
    assert not missing, f"settings without an AUOREO_* line: {missing}"


def test_every_declared_key_is_listed() -> None:
    text = EXAMPLE.read_text(encoding="utf-8")
    listed = {n for n, _ in _assignments()}
    declared = {k for k in _declared_keys() if "/" not in k}  # `a/b` names live in secrets.db only
    missing = sorted(k for k in declared if k not in listed and k not in text)
    assert not missing, f"keys a tool/backend/plugin reads but .env.example does not list: {missing}"
    assert {"OPENROUTER_API_KEY", "ANTHROPIC_API_KEY", "EXA_API_KEY", "E2B_API_KEY"} <= listed
    for slashed in ("telegram/bot_token", "discord/bot_token", "email/password"):
        assert slashed in text  # documented as `auoreo secrets set <name>`


def test_only_project_safe_names_carry_a_value() -> None:
    """Copying the example as a project `.env` must never set (or warn about) anything else."""
    filled = {n: v for n, v in _assignments() if v.strip()}
    assert filled, "the example should keep a sensible default model"
    for name, value in filled.items():
        assert dotenv.project_allowed(name) and not dotenv.is_protected(name), name
        assert not name.endswith(("_KEY", "_TOKEN", "_SECRET", "_PASSWORD")), f"{name} must stay blank"
        assert "secret" not in value.lower(), name


def test_tags_match_the_loader() -> None:
    lines = EXAMPLE.read_text(encoding="utf-8").splitlines()
    for i, line in enumerate(lines):
        m = ASSIGN.match(line)
        if not m:
            continue
        comment = lines[i - 1] if i and lines[i - 1].startswith("#") else ""
        name = m.group(1)
        if dotenv.is_protected(name):
            assert comment.endswith("[env-only]"), name
        elif not dotenv.project_allowed(name):
            assert comment.endswith("[home]"), name
        else:
            assert not comment.endswith(("[home]", "[env-only]")), name


def test_copying_the_example_as_a_project_env_is_quiet(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, caplog: pytest.LogCaptureFixture
) -> None:
    (tmp_path / ".env").write_text(EXAMPLE.read_text(encoding="utf-8"), encoding="utf-8")
    monkeypatch.setenv("AUOREO_HOME", str(tmp_path / "home"))
    names = {n for n, _ in _assignments()}
    for name in names:
        if name != "AUOREO_HOME":
            monkeypatch.delenv(name, raising=False)
    with caplog.at_level(logging.WARNING, logger="auoreo.core.dotenv"):
        loaded = dotenv.load_env_files(tmp_path)
    assert not [r for r in caplog.records if r.levelno >= logging.WARNING], caplog.text
    assert set(loaded) == {n for n, v in dotenv_values(tmp_path / ".env").items() if v}
    assert os.environ.get("AUOREO_YOLO") is None and os.environ.get("AUOREO_PERMISSION_MODE") is None
